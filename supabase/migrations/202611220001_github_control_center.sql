
create extension if not exists pgcrypto;

-- --------------------------------------------------
-- GITHUB ACCOUNTS
-- --------------------------------------------------

create table if not exists public.github_accounts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  github_id bigint not null,
  login text not null,
  name text,
  email text,
  avatar_url text not null,
  profile_url text not null,
  account_type text not null default 'User',
  scopes text[] not null default '{}',
  encrypted_token jsonb not null,
  connected_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  token_expires_at timestamptz,
  unique (user_id, github_id)
);

alter table public.github_accounts
  add column if not exists email text;

alter table public.github_accounts
  add column if not exists token_expires_at timestamptz;

create index if not exists github_accounts_user_id_idx
  on public.github_accounts(user_id);

alter table public.github_accounts enable row level security;

drop policy if exists "read own github accounts"
  on public.github_accounts;

drop policy if exists "Users can view their own GitHub accounts"
  on public.github_accounts;

create policy "Users can view their own GitHub accounts"
  on public.github_accounts
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

revoke all on public.github_accounts from anon, authenticated;
grant select on public.github_accounts to authenticated;

-- --------------------------------------------------
-- GITHUB OAUTH STATES
-- --------------------------------------------------

create table if not exists public.github_oauth_states (
  state text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists github_oauth_states_expires_at_idx
  on public.github_oauth_states(expires_at);

alter table public.github_oauth_states enable row level security;

revoke all on public.github_oauth_states from anon, authenticated;

-- --------------------------------------------------
-- ATOMIC OAUTH STATE CONSUMPTION
-- --------------------------------------------------

create or replace function public.consume_github_oauth_state(
  p_state text
)
returns table (
  user_id uuid,
  expires_at timestamptz
)
language sql
security definer
set search_path = ''
as $$
  delete from public.github_oauth_states
  where state = p_state
    and expires_at > now()
  returning
    github_oauth_states.user_id,
    github_oauth_states.expires_at;
$$;

revoke all on function public.consume_github_oauth_state(text)
  from public, anon, authenticated;

grant execute on function public.consume_github_oauth_state(text)
  to service_role;

-- --------------------------------------------------
-- AUDIT LOGS
-- --------------------------------------------------

create table if not exists public.audit_logs (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  resource_type text,
  resource_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists audit_logs_user_created_idx
  on public.audit_logs(user_id, created_at desc);

alter table public.audit_logs enable row level security;

drop policy if exists "read own audit logs"
  on public.audit_logs;

drop policy if exists "Users can view their own audit logs"
  on public.audit_logs;

create policy "Users can view their own audit logs"
  on public.audit_logs
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

revoke all on public.audit_logs from anon, authenticated;
grant select on public.audit_logs to authenticated;
